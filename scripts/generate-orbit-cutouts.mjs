// Makes transparent cut-outs of the demo product photos for the home page orbit:
// public/demo/fashion/<name>.webp → public/demo/fashion/cutout/<name>.webp.
// The photos sit on a light grey backdrop with a soft spotlight, so a flood fill
// from the edges that follows the smooth shading finds it and stops at the outline.
// Usage: node scripts/generate-orbit-cutouts.mjs
import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const SRC = "public/demo/fashion";
const OUT = path.join(SRC, "cutout");
const SIZE = 480;
const STEP = 7; // largest colour jump between neighbouring backdrop pixels (it is a soft gradient)
const MIN_LIGHT = 185; // backdrop pixels are light…
const MAX_CHROMA = 22; // …and nearly grey
const HOLE_LIGHT = 222; // enclosed areas (inside a bag handle) this light and grey are cut too…
const HOLE_CHROMA = 10;
const MIN_HOLE = 300; // …if at least this many pixels
// White products melt into a white backdrop, so they keep their normal photo.
const KEEP_PHOTO = new Set(["charger-white", "earbuds-white", "tee-white", "sneaker-white", "smartwatch-silver", "clearcase-clear"]);

const skip = (f) => !f.endsWith(".webp") || /^(category-|cutout-|hero|promo)/.test(f) || KEEP_PHOTO.has(f.replace(".webp", ""));

async function cutout(file) {
  const { data, info } = await sharp(path.join(SRC, file)).resize(SIZE, SIZE, { fit: "cover" }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const step = (i, j) => Math.max(Math.abs(data[i] - data[j]), Math.abs(data[i + 1] - data[j + 1]), Math.abs(data[i + 2] - data[j + 2]));
  const backdropLike = (i) => {
    const lo = Math.min(data[i], data[i + 1], data[i + 2]);
    return lo >= MIN_LIGHT && Math.max(data[i], data[i + 1], data[i + 2]) - lo <= MAX_CHROMA;
  };

  // Flood fill from the edges, following the backdrop's smooth shading and
  // stopping at the product outline.
  const seen = new Uint8Array(w * h);
  const stack = [];
  const visit = (p, from) => {
    if (seen[p] || !backdropLike(p * 4) || (from >= 0 && step(p * 4, from * 4) > STEP)) return;
    seen[p] = 1;
    stack.push(p);
  };
  for (let x = 0; x < w; x++) visit(x, -1), visit((h - 1) * w + x, -1);
  for (let y = 0; y < h; y++) visit(y * w, -1), visit(y * w + w - 1, -1);
  while (stack.length) {
    const p = stack.pop();
    const x = p % w, y = (p / w) | 0;
    if (x > 0) visit(p - 1, p);
    if (x < w - 1) visit(p + 1, p);
    if (y > 0) visit(p - w, p);
    if (y < h - 1) visit(p + w, p);
  }

  // Holes: enclosed regions of backdrop (inside bag handles).
  const holeLike = (i) => {
    const lo = Math.min(data[i], data[i + 1], data[i + 2]);
    return lo >= HOLE_LIGHT && Math.max(data[i], data[i + 1], data[i + 2]) - lo <= HOLE_CHROMA;
  };
  const hole = new Uint8Array(w * h);
  for (let start = 0; start < w * h; start++) {
    if (seen[start] || hole[start] || !holeLike(start * 4)) continue;
    const region = [start];
    hole[start] = 1;
    for (let k = 0; k < region.length; k++) {
      const p = region[k], x = p % w, y = (p / w) | 0;
      for (const q of [x > 0 && p - 1, x < w - 1 && p + 1, y > 0 && p - w, y < h - 1 && p + w]) {
        if (q === false || seen[q] || hole[q] || !holeLike(q * 4)) continue;
        hole[q] = 1;
        region.push(q);
      }
    }
    if (region.length >= MIN_HOLE) for (const p of region) seen[p] = 1;
  }

  // Transparent backdrop, with a one-pixel soft edge so the outline is not jagged.
  const alpha = new Uint8Array(w * h);
  for (let p = 0; p < w * h; p++) alpha[p] = seen[p] ? 0 : 255;
  for (let p = 0; p < w * h; p++) {
    if (!alpha[p]) continue;
    const x = p % w, y = (p / w) | 0;
    const edge = (x > 0 && !alpha[p - 1]) || (x < w - 1 && !alpha[p + 1]) || (y > 0 && !alpha[p - w]) || (y < h - 1 && !alpha[p + w]);
    data[p * 4 + 3] = edge ? 140 : 255;
  }
  for (let p = 0; p < w * h; p++) if (!alpha[p]) data[p * 4 + 3] = 0;

  await sharp(data, { raw: { width: w, height: h, channels: 4 } })
    .trim({ threshold: 0 })
    .resize(SIZE, SIZE, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .webp({ quality: 82, alphaQuality: 90 })
    .toFile(path.join(OUT, file));
}

await mkdir(OUT, { recursive: true });
const files = (await readdir(SRC)).filter((f) => !skip(f));
for (const f of files) await cutout(f);
await writeFile(
  "src/features/catalog/orbit-cutouts.ts",
  `// Generated by scripts/generate-orbit-cutouts.mjs — demo photos that have a transparent cut-out.
export const ORBIT_CUTOUTS = new Set<string>(${JSON.stringify(files.map((f) => f.replace(".webp", "")))});
`,
);
console.log(`Wrote ${files.length} cut-outs to ${OUT}`);
